export function translateWeatherCondition(cond, lang) {
  if (!cond || !lang || lang === 'en') return cond;
  return weatherConditionTranslations[lang]?.[cond] || cond;
}

export function translateDay(dayName, lang) {
  if (!dayName || !lang || lang === 'en') return dayName;
  return dayTranslations[lang]?.[dayName] || dayName;
}

// Helper function to get translation for selected language code with fallback to English
export function getTranslation(code) {
  const base = translations[code];
  const fallback = translations.en;
  if (!base) return fallback;
  return { ...fallback, ...base };
}
